def main():
    w = json.load(open(PATH, encoding='utf-8'))
    first = [re.split(r'\s*[=,(]\s*', x[0])[0].strip() for x in w]
    by = {}
    for i, f in enumerate(first): by.setdefault(f, []).append(i)
    zone = [None] * len(w)
    unknown, clash = [], []
    for z, (name, text) in enumerate(THEMES):
        for t in [t.replace('_', ' ') for t in text.split()]:
            if '#' in t:
                t, n = t.split('#'); ids = [int(n)]
            else:
                ids = by.get(t)
                if not ids: unknown.append((name, t)); continue
                ids = [i for i in ids if zone[i] is None][:1] or ids[:1]
            for i in ids:
                if zone[i] is not None and zone[i] != z: clash.append((t, THEMES[zone[i]][0], name))
                elif zone[i] is None: zone[i] = z
    counts = [zone.count(z) for z in range(len(THEMES))]
    print('counts', {THEMES[z][0]: c for z, c in enumerate(counts)})
    print('unknown', unknown)
    print('clash', clash)
    left = [f'{i}|{w[i][0]}|{w[i][3]}' for i in range(len(w)) if zone[i] is None]
    print('unassigned', len(left)); print('\n'.join(left))
    if '--write' in sys.argv:
        assert all(c == 40 for c in counts) and not left and not clash, 'not balanced'
        for i, x in enumerate(w): x[5] = zone[i]
        json.dump(w, open(PATH, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
        print('written')


main()
